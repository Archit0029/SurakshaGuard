// SurakshaPay — Core Type Definitions
// Maps conceptually to Android security service interfaces
// ─────────────────────────────────────────────────────────────────────────────

/** Threat severity levels used throughout the system */
export type ThreatLevel = 'SAFE' | 'LOW' | 'MEDIUM' | 'HIGH' | 'CRITICAL';

/**
 * Interception State Machine states.
 *
 * In a real Android implementation, these map to:
 * - IDLE: App in background, AccessibilityService passively monitoring
 * - LISTENING_ANALYZING: CallScreeningService active, SpeechRecognizer transcribing
 * - TRANSACTION_INITIATED: UPI intent detected via AccessibilityService
 * - PRE_AUTH_FROZEN: AccessibilityService blocks PIN entry overlay
 * - TRANSACTION_ABORTED: User heeded warning, transaction cancelled
 * - TRANSACTION_PERMITTED: Risk cleared or user override, PIN entry allowed
 */
export type InterceptionState =
  | 'IDLE'
  | 'LISTENING_ANALYZING'
  | 'TRANSACTION_INITIATED'
  | 'PRE_AUTH_FROZEN'
  | 'TRANSACTION_ABORTED'
  | 'TRANSACTION_PERMITTED';

/** Multi-factor risk breakdown from the scoring engine */
export interface RiskBreakdown {
  /** NLP urgency/coercion score (0-100), weighted 35% */
  urgencyScore: number;
  /** Device state risk — screen sharing, suspicious apps (0-100), weighted 35% */
  deviceRiskScore: number;
  /** VPA reputation score (0-100), weighted 30% */
  vpaRiskScore: number;
  /** Weighted composite score (0-100) */
  totalScore: number;
  /** Specific keywords/phrases that triggered the urgency score */
  detectedKeywords: string[];
  /** Dangerous apps detected on device */
  detectedApps: string[];
  /** Whether the recipient VPA is in a verified merchant directory */
  vpaVerified: boolean;
  /** Computed threat level from totalScore */
  threatLevel: ThreatLevel;
}

/** Pre-configured scam simulation scenario for demo */
export interface ScamScenario {
  id: string;
  name: string;
  description: string;
  icon: string;
  /** Simulated call/conversation transcript fed to the NLP engine */
  transcript: string;
  /** Optional SMS content displayed on the phone */
  smsContent?: string;
  /** Caller ID shown during the simulation */
  callerID?: string;
  /** Simulated active apps (e.g., AnyDesk, TeamViewer) */
  activeApps: string[];
  /** Recipient Virtual Payment Address */
  recipientVPA: string;
  /** Display name for the recipient */
  recipientName: string;
  /** Payment amount in INR */
  amount: number;
  /** Whether this VPA is in the verified merchant directory */
  isVPAVerified: boolean;
  /** UI color hint: 'green' | 'red' | 'yellow' */
  threatColor: string;
}

/** Vernacular warning generated by the explainability agent */
export interface VernacularWarning {
  /** Warning script in English */
  english: string;
  /** Warning script in Hindi */
  hindi: string;
  /** List of specific threat triggers that caused this warning */
  triggers: string[];
  /** Recommended action for the user */
  recommendedAction: string;
}

/** Timeline event for the real-time analysis feed */
export interface TimelineEvent {
  id: string;
  timestamp: Date;
  type: 'info' | 'warning' | 'danger' | 'success';
  message: string;
  detail?: string;
}

/** Top-level application state managed by the App reducer */
export interface AppState {
  currentScenario: ScamScenario | null;
  interceptionState: InterceptionState;
  riskBreakdown: RiskBreakdown | null;
  warning: VernacularWarning | null;
  timeline: TimelineEvent[];
  language: 'en' | 'hi';
  isAnalyzing: boolean;
  showPinDialog: boolean;
  showLockOverlay: boolean;
}

/** Actions dispatched to the App reducer */
export type AppAction =
  | { type: 'SELECT_SCENARIO'; scenario: ScamScenario }
  | { type: 'START_ANALYSIS' }
  | { type: 'ANALYSIS_COMPLETE'; risk: RiskBreakdown; warning: VernacularWarning | null }
  | { type: 'INITIATE_PAYMENT' }
  | { type: 'FREEZE_TRANSACTION' }
  | { type: 'ABORT_TRANSACTION' }
  | { type: 'PERMIT_TRANSACTION' }
  | { type: 'RESET' }
  | { type: 'TOGGLE_LANGUAGE' }
  | { type: 'ADD_TIMELINE_EVENT'; event: TimelineEvent };

